from __future__ import annotations

import asyncio
from pathlib import Path
from typing import Protocol

from app.config import Settings


class BlobStore(Protocol):
    async def put(self, key: str, data: bytes) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...


class LocalBlobStore:
    """Files on a local volume (dev, tests, single-VM deployments)."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if self.root not in path.parents:  # blocks "../" tricks even though keys are generated by us
            raise ValueError("invalid blob key")
        return path

    async def put(self, key: str, data: bytes) -> None:
        path = self._path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

        await asyncio.to_thread(write)

    async def get(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)

    async def delete(self, key: str) -> None:
        def remove() -> None:
            self._path(key).unlink(missing_ok=True)

        await asyncio.to_thread(remove)


class S3BlobStore:
    """S3 objects (prod). boto3 is imported lazily so it is only needed when this backend is used."""

    def __init__(self, bucket: str) -> None:
        import boto3

        self.bucket = bucket
        self.client = boto3.client("s3")

    async def put(self, key: str, data: bytes) -> None:
        await asyncio.to_thread(self.client.put_object, Bucket=self.bucket, Key=key, Body=data)

    async def get(self, key: str) -> bytes:
        response = await asyncio.to_thread(self.client.get_object, Bucket=self.bucket, Key=key)
        body: bytes = await asyncio.to_thread(response["Body"].read)
        return body

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self.client.delete_object, Bucket=self.bucket, Key=key)


def build_blob_store(settings: Settings) -> BlobStore:
    inner: BlobStore = (
        S3BlobStore(settings.s3_bucket) if settings.storage_backend == "s3" else LocalBlobStore(settings.storage_path)
    )
    if not settings.vault_enabled:
        return inner
    from app.storage.vault import VaultBlobStore, load_keyring  # lazy: vault.py imports this module

    return VaultBlobStore(inner, load_keyring(settings))  # raises VaultError at startup if the key is unusable
